/*
    Stworzymy sobie teraz 3 oddzielne role dla kadzego oddzialu:
        - Rola ENGINEERING__MANAGER bedzie mogla czytac jedynie dane o Engineering
        - Rola CUSTOMER_SUPPORT__MANAGER bedzie mogla czytac jedynie dane o Customer Support
        - Rola FINANCE__READER bedzie mogla czytac wszystko
