GRANT ROLE BLAZEJ_CUSTOMER_SUPPORT__MANAGER TO ROLE BLAZEJ__ADMIN;
GRANT ROLE BLAZEJ_FINANCE__READER TO ROLE BLAZEJ__ADMIN;



USE ROLE BLAZEJ__ADMIN;
GRANT USAGE ON SCHEMA BLAZEJ_DB.CORE TO ROLE BLAZEJ_ENGINEERING__MANAGER;
GRANT USAGE ON SCHEMA BLAZEJ_DB.CORE TO ROLE BLAZEJ_CUSTOMER_SUPPORT__MANAGER;
GRANT USAGE ON SCHEMA BLAZEJ_DB.CORE TO ROLE BLAZEJ_FINANCE__READER;

GRANT SELECT ON TABLE BLAZEJ_DB.CORE.EMPLOYEE TO ROLE BLAZEJ_ENGINEERING__MANAGER;
GRANT SELECT ON TABLE BLAZEJ_DB.CORE.EMPLOYEE TO ROLE BLAZEJ_CUSTOMER_SUPPORT__MANAGER;
GRANT SELECT ON TABLE BLAZEJ_DB.CORE.EMPLOYEE TO ROLE BLAZEJ_FINANCE__READER;

GRANT USAGE ON WAREHOUSE BLAZEJ_READER__XS_WH TO ROLE BLAZEJ_ENGINEERING__MANAGER;
GRANT USAGE ON WAREHOUSE BLAZEJ_READER__XS_WH TO ROLE BLAZEJ_CUSTOMER_SUPPORT__MANAGER;
GRANT USAGE ON WAREHOUSE BLAZEJ_READER__XS_WH TO ROLE BLAZEJ_FINANCE__READER;

CREATE OR REPLACE ROW ACCESS POLICY BLAZEJ_DB.CORE.DEPARTMENT_FILTER
AS (DEPARTMENT TEXT) RETURNS BOOLEAN ->
    CURRENT_ROLE() IN ('BLAZEJ__ADMIN', 'BLAZEJ__READER', 'BLAZEJ_FINANCE__READER')
    OR (DEPARTMENT = 'Engineering' AND 'BLAZEJ_ENGINEERING__MANAGER' = CURRENT_ROLE())
    OR (DEPARTMENT = 'Customer Support' AND 'BLAZEJ_CUSTOMER_SUPPORT__MANAGER' = CURRENT_ROLE());

ALTER TABLE BLAZEJ_DB.CORE.EMPLOYEE
    ADD ROW ACCESS POLICY BLAZEJ_DB.CORE.DEPARTMENT_FILTER
    ON (DEPARTMENT);


