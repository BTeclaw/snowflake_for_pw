    Wyobrazmy sobie ze takich tabelek mozemy miec wiecej, wiec dobrze byloby gdyby
    zamiast bezposrednio przypisywac polityke maskujaca pod kolumne, przypisac ja
    do Taga, ktory mozna nadawac i zdejmowac w latwiejszy sposob - a przede wszystkim => sledzic gdzie zostal on nadany!
