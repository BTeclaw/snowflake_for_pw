-- Stworzmy tag ktory bedzie kategoryzowal PII -> NORMAL_PII / EMAIL

USE ROLE BLAZEJ__ADMIN;

CREATE OR REPLACE TAG BLAZEJ_DB.CORE.PII_CATEGORY
    ALLOWED_VALUES 'NORMAL_PII', 'EMAIL';
-- Utworzmy politke ktora maskuje w zaleznosci od taga
CREATE OR REPLACE MASKING POLICY BLAZEJ_DB.CORE.PII_MASKING_POLICY AS
(val string) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('PAYROLL_ANALYST') AND SYSTEM$GET_TAG_ON_CURRENT_COLUMN('BLAZEJ_DB.CORE.PII_CATEGORY') = 'NORMAL_PII' THEN '***MASKED***'
        WHEN CURRENT_ROLE() IN ('PAYROLL_ANALYST') AND  SYSTEM$GET_TAG_ON_CURRENT_COLUMN('BLAZEJ_DB.CORE.PII_CATEGORY') = 'EMAIL' THEN REGEXP_REPLACE(val, '^[^@]+', '*****')
        ELSE VAL
    END;

-- Nastepnie nadajmy polityke aby byla aplikowana razem z Tagiem
ALTER TAG BLAZEJ_DB.CORE.PII_CATEGORY SET MASKING POLICY BLAZEJ_DB.CORE.PII_MASKING_POLICY;

