-- Utworzmy Masking Policy
USE ROLE BLAZEJ__ADMIN;
/*
    Polityka maskuajca bedzie zwracac na maskowanej kolumnie ***MASKED***,
    jezeli ansza rola jest PAYROLL_ANALYST, w przeciwnym razie zwroci nie
    zamaskowana wartosc
*/
CREATE MASKING POLICY BLAZEJ_DB.CORE.PII_MASKING_POLICY AS
(val string) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('PAYROLL_ANALYST') THEN '***MASKED***'
        ELSE VAL
    END;

-- Zaaplikujmy polityke maskujaca na tabele

ALTER TABLE BLAZEJ_DB.CORE.EMPLOYEE MODIFY
    COLUMN FIRST_NAME SET MASKING POLICY BLAZEJ_DB.CORE.PII_MASKING_POLICY,
    COLUMN LAST_NAME  SET MASKING POLICY BLAZEJ_DB.CORE.PII_MASKING_POLICY,
    COLUMN PHONE  SET MASKING POLICY BLAZEJ_DB.CORE.PII_MASKING_POLICY,
    COLUMN EMAIL  SET MASKING POLICY BLAZEJ_DB.CORE.PII_MASKING_POLICY;

-- Widzimy zamaskowane wartosci
USE ROLE PAYROLL_ANALYST;
USE SECONDARY ROLES NONE;
SELECT * FROM BLAZEJ_DB.CORE.EMPLOYEE;


/*
